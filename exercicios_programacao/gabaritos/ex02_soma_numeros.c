#include <stdio.h> // Inclui a biblioteca padrão de entrada e saída

int main() { // Função principal
    int num1 = 10; // Declara e inicializa a primeira variável inteira
    int num2 = 20; // Declara e inicializa a segunda variável inteira
    int soma;      // Declara uma variável para armazenar a soma

    soma = num1 + num2; // Realiza a soma dos dois números

    printf("A soma de %d e %d é: %d\n", num1, num2, soma); // Imprime o resultado da soma
    return 0; // Retorna 0 para indicar sucesso
}
